CREATE TABLE bills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commodity TEXT NOT NULL CHECK (commodity IN ('power', 'gas')),
    supplier TEXT,
    period_start TEXT NOT NULL,
    period_end TEXT NOT NULL,
    consumption DOUBLE PRECISION,
    kwh_f1 DOUBLE PRECISION, kwh_f2 DOUBLE PRECISION, kwh_f3 DOUBLE PRECISION,
    mc DOUBLE PRECISION, coeff_c DOUBLE PRECISION,
    power_kw DOUBLE PRECISION,
    reading_type TEXT CHECK (reading_type IN ('effettiva', 'stimata')),
    total_eur DOUBLE PRECISION,
    annual_consumption DOUBLE PRECISION,
    annual_f1 DOUBLE PRECISION, annual_f2 DOUBLE PRECISION, annual_f3 DOUBLE PRECISION,
    annual_spend DOUBLE PRECISION,
    pdf_path TEXT,
    social_bonus_expires_on TEXT,
    max_power_kw DOUBLE PRECISION,
    annual_max_power_kw DOUBLE PRECISION,
    power_rate_kw_month DOUBLE PRECISION,
    profile_id INTEGER REFERENCES profiles(id),
    created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX bills_profile ON bills(profile_id);

CREATE TABLE offers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commodity TEXT NOT NULL CHECK (commodity IN ('power', 'gas')),
    supplier TEXT NOT NULL,
    name TEXT NOT NULL,
    price_type TEXT NOT NULL CHECK (price_type IN ('fixed', 'indexed')),
    price DOUBLE PRECISION,
    price_f1 DOUBLE PRECISION, price_f2 DOUBLE PRECISION, price_f3 DOUBLE PRECISION,
    avg_price DOUBLE PRECISION,
    spread DOUBLE PRECISION,
    fixed_fee_month DOUBLE PRECISION,
    power_fee_kw_month DOUBLE PRECISION,
    one_off_discount DOUBLE PRECISION,
    expires_on TEXT,
    is_current INTEGER NOT NULL DEFAULT 0,
    source TEXT,
    loss_pct DOUBLE PRECISION,
    dispatching DOUBLE PRECISION,
    capacity DOUBLE PRECISION,
    gas_mgmt DOUBLE PRECISION,
    pcs_adjustment DOUBLE PRECISION,
    dispatching_extra INTEGER NOT NULL DEFAULT 0,
    zones TEXT,
    dual_with TEXT,
    duration_months INTEGER,
    started_on TEXT,
    conditions TEXT,
    after_term TEXT,
    profile_id INTEGER REFERENCES profiles(id),
    created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

-- il valore è testo: numeri e codici ISTAT convivono, chi legge converte
CREATE TABLE settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE index_factors (
    index_name TEXT NOT NULL CHECK (index_name IN ('pun', 'psv')),
    month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    factor DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (index_name, month)
);

CREATE TABLE proposals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id INTEGER NOT NULL REFERENCES profiles(id),
    commodity TEXT NOT NULL,
    terms TEXT NOT NULL,
    contact TEXT,
    received_on TEXT,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE INDEX proposals_profile ON proposals(profile_id);

CREATE TABLE bill_layouts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    signature TEXT NOT NULL,
    rules TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
