-- Schema completo equivalente alle migrazioni SQLite 001-011 (un'installazione PostgreSQL nasce già aggiornata).
-- Da qui in poi ogni modifica ha lo stesso numero in sqlite/ e in postgres/.
CREATE TABLE profiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    region TEXT NOT NULL DEFAULT '',
    province TEXT NOT NULL DEFAULT '',
    comune TEXT NOT NULL DEFAULT '',
    default_power_kw DOUBLE PRECISION NOT NULL DEFAULT 3.0,
    created_at TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
